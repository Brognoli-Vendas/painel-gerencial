create table if not exists public.painel_segredo (id integer not null default 1 primary key, valor text not null);
create table if not exists public.atend_segredo (valor text not null);
create table if not exists public.painel_snapshot (chave text primary key, dados jsonb not null, atualizado_em timestamptz not null default now());
create table if not exists public.vendas_temporarias (
  deal_id text primary key, linha jsonb not null, motivo text,
  criado_em timestamptz not null default now(), expira_em timestamptz not null default (now() + interval '3 days'));
create table if not exists public.atend_estado (
  deal_id bigint primary key, assigned integer, stage text, cat text, src text, atualizado timestamptz not null default now());
create table if not exists public.atend_eventos (
  id bigint generated by default as identity primary key, deal_id bigint not null, ts timestamptz not null,
  assigned integer, stage text, cat text, src text, tipo text not null);
create index if not exists atend_eventos_deal_ts on public.atend_eventos (deal_id, ts, id);
create index if not exists atend_eventos_ts on public.atend_eventos (ts);
alter table public.painel_segredo enable row level security;
alter table public.atend_segredo enable row level security;
alter table public.painel_snapshot enable row level security;
alter table public.vendas_temporarias enable row level security;
alter table public.atend_estado enable row level security;
alter table public.atend_eventos enable row level security;

create or replace function public.snapshot_gravar(p_segredo text, p_chave text, p_dados jsonb) returns void
language plpgsql security definer set search_path to 'public' as $$
begin
  if not exists (select 1 from painel_segredo where valor = p_segredo) then raise exception 'negado'; end if;
  insert into painel_snapshot(chave, dados, atualizado_em) values (p_chave, p_dados, now())
  on conflict (chave) do update set dados = excluded.dados, atualizado_em = now();
end $$;

create or replace function public.snapshot_ler(p_segredo text, p_chave text)
returns table(dados jsonb, atualizado_em timestamptz) language plpgsql security definer set search_path to 'public' as $$
begin
  if not exists (select 1 from painel_segredo where valor = p_segredo) then raise exception 'negado'; end if;
  return query select s.dados, s.atualizado_em from painel_snapshot s where s.chave = p_chave;
end $$;

create or replace function public.vendas_temp_ler(p_segredo text)
returns table(deal_id text, linha jsonb) language plpgsql security definer set search_path to 'public' as $$
begin
  if not exists (select 1 from painel_segredo where valor = p_segredo) then raise exception 'negado'; end if;
  return query select t.deal_id, t.linha from vendas_temporarias t where t.expira_em > now() order by t.criado_em;
end $$;

create or replace function public.registrar_falha_login(p_segredo text, p_email text) returns void
language plpgsql security definer set search_path to 'public' as $$
declare v_email text := lower(trim(coalesce(p_email, ''))); v_uid uuid;
begin
  if not exists (select 1 from painel_segredo where valor = p_segredo) then raise exception 'negado'; end if;
  if v_email = '' or length(v_email) > 254 then return; end if;
  select id into v_uid from auth.users where lower(email) = v_email limit 1;
  if (select count(*) from registros_acesso where evento = 'falha_login' and detalhe->>'email' = v_email and criado_em > now() - interval '1 hour') >= 30 then return; end if;
  insert into registros_acesso(usuario_id, evento, tela, detalhe)
  values (v_uid, 'falha_login', 'Login', jsonb_build_object('email', v_email, 'cadastrado', v_uid is not null));
end $$;
